// Model gallery for the look lane: every building of one epoch on a lawn, or one with ?t=<type>; ?a=<age> dresses them for a side age. See shoot.mjs.
import * as THREE from 'three';
import { buildingGeometry } from '../../src/render/buildingModels';
import { BUILDING_TYPES } from '../../src/sim/data';
import type { AgeId } from '../../src/sim/types';
const q = new URLSearchParams(location.search);
const epoch = +(q.get('e') ?? 0);
const only = q.get('t');
const age = (q.get('a') ?? undefined) as AgeId | undefined;
const W = 1600, H = 1000;
const r = new THREE.WebGLRenderer({ canvas: document.getElementById('c') as HTMLCanvasElement, antialias: true, preserveDrawingBuffer: true });
r.setSize(W, H); r.setClearColor(0x8fa8b8);
const scene = new THREE.Scene();
scene.add(new THREE.HemisphereLight(0xffffff, 0x556655, 1.6));
const sun = new THREE.DirectionalLight(0xfff0d0, 2.2); sun.position.set(-5, 10, 6); scene.add(sun);
const types = only ? [only] : BUILDING_TYPES;
const cols = Math.min(6, types.length), rows = Math.ceil(types.length / cols);
const ground = new THREE.Mesh(new THREE.PlaneGeometry(200, 200).rotateX(-Math.PI / 2), new THREE.MeshLambertMaterial({ color: 0x6f8a55 }));
scene.add(ground);
const sp = only ? 0 : 8;
types.forEach((t, i) => {
  const g = buildingGeometry(t, epoch, '#cc3333', 0, age);
  const m = new THREE.Mesh(g, new THREE.MeshLambertMaterial({ vertexColors: true }));
  m.position.set((i % cols - (cols - 1) / 2) * sp, 0, (Math.floor(i / cols) - (rows - 1) / 2) * sp);
  scene.add(m);
});
const cam = new THREE.PerspectiveCamera(only ? 35 : 38, W / H, 0.1, 500);
const d = only ? 12 : 40;
cam.position.set(d * 0.55, d * 0.7, d * 0.75); cam.lookAt(0, only ? 1.5 : 0, 0);
r.render(scene, cam);
(window as any).done = true;
